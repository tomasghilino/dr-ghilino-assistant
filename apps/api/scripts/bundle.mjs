// Bundle the InsForge function (ADR 0001): our code (apps/api + packages/core) becomes one ESM
// file; third-party packages stay as `npm:<name>@<exact version>` imports that Deno resolves, so we
// never ship a minified copy of the Anthropic or InsForge SDKs.
//
//   pnpm --filter @ghilino/api bundle   → apps/api/dist/chat-api.js
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const apiRoot = join(here, "..");
const coreRoot = join(apiRoot, "../../packages/core");

/** Exact installed version of a package, resolved from the package that imports it. */
function versionOf(name, fromDir) {
  const require = createRequire(join(fromDir, "package.json"));
  let dir = dirname(require.resolve(name));
  for (;;) {
    try {
      const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      if (pkg.name === name) return pkg.version;
    } catch {}
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`cannot find the version of ${name}`);
    dir = parent;
  }
}

const npmImports = {
  name: "npm-specifiers",
  setup(builder) {
    builder.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith("@ghilino/")) return undefined; // our code: bundle it
      if (args.path.startsWith("node:")) {
        throw new Error(`node built-in ${args.path} imported by ${args.importer}`);
      }
      const parts = args.path.split("/");
      const name = args.path.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
      const subpath = args.path.slice(name.length);
      const fromDir = args.importer.includes("/packages/core/") ? coreRoot : apiRoot;
      return { path: `npm:${name}@${versionOf(name, fromDir)}${subpath}`, external: true };
    });
  },
};

const result = await build({
  entryPoints: [join(apiRoot, "src/insforge.ts")],
  outfile: join(apiRoot, "dist/chat-api.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  conditions: ["deno", "worker", "browser", "import"],
  mainFields: ["module", "main"],
  plugins: [npmImports],
  metafile: true,
  legalComments: "none",
  banner: { js: "// Generated by apps/api/scripts/bundle.mjs. Do not edit." },
});

const externals = new Set();
for (const output of Object.values(result.metafile.outputs)) {
  for (const imported of output.imports) if (imported.external) externals.add(imported.path);
}
const size = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
console.log(`apps/api/dist/chat-api.js: ${(size / 1024).toFixed(1)} KiB`);
console.log(`npm imports:\n  ${[...externals].sort().join("\n  ")}`);
